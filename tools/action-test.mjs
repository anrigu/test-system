import { createRequire } from 'node:module';
const { chromium, devices } = createRequire(import.meta.url)('playwright');
const [,, mom, dad, outDir] = process.argv;
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await (await browser.newContext({ ...devices['iPhone 13'], deviceScaleFactor: 1 })).newPage();
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('http://localhost:8173/');
await page.locator('.parent[data-who="mom"] input[type=file]:not([capture])').setInputFiles(mom);
await page.locator('.parent[data-who="dad"] input[type=file]:not([capture])').setInputFiles(dad);
await page.waitForSelector('#results:not([hidden])', { timeout: 60000 });
await page.click('#play'); await page.waitForTimeout(3000);
console.log('playing age label:', await page.textContent('#ageLabel'));
await page.click('#play');
await page.click('#saveImg'); await page.waitForSelector('#preview:not([hidden])');
console.log('save image preview:', await page.getAttribute('#previewMedia img', 'alt'));
await page.click('#previewClose');
await page.click('#savePoster'); await page.waitForSelector('#preview:not([hidden])');
await page.locator('#previewMedia img').screenshot({ path: `${outDir}/poster.png` });
await page.click('#previewClose');
console.log('video button hidden?', await page.isHidden('#saveVideo'));
await page.click('#saveVideo');
await page.waitForSelector('#preview:not([hidden])', { timeout: 120000 });
await page.waitForTimeout(1500);
console.log('video saved; preview shows:', await page.evaluate(() => document.querySelector('#previewMedia video') ? 'video element' : document.querySelector('#previewHint').textContent));
await page.click('#previewClose');
// reload: photos restored from IndexedDB?
await page.reload();
await page.waitForSelector('#results:not([hidden])', { timeout: 60000 });
console.log('restored after reload: yes');
console.log(errors.length ? 'ERRORS:\n' + errors.join('\n') : 'no errors');
await browser.close();
